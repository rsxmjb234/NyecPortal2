"""
build_reports.py — regenerate hosp_data.js from the latest Athena JSON.
Run this after re-executing reportonhospitals.sql to refresh the page data.
"""
import json

SRC  = 'SQLExamples/reportonhospitals.json'
DEST = 'hosp_data.js'

with open(SRC) as f:
    raw = json.load(f)

# Compact rows: [qe, org_name, aa_code, ccd_int, trn_int]
rows = []
for r in raw['rows']:
    rows.append([
        r['qe_name'],
        r['organization_name'],
        r['assigning_authority'],
        int(r['ccd_count']),
        int(r['trn_count']),
    ])

# QEs ordered by total volume (descending)
from collections import defaultdict
qe_totals = defaultdict(int)
for r in rows:
    qe_totals[r[0]] += r[3] + r[4]
qes = sorted(qe_totals, key=lambda q: -qe_totals[q])

payload = {
    'qes':  qes,
    'rows': rows,
    'meta': {
        'scanned_gb': raw['scanned_gb'],
        'row_count':  raw['row_count'],
        # Window: 10 days ending at snapshot (5 days ago)
        # Display dates are derived at query time; update manually if re-run on a new date.
        'window_label': 'Nov\u00a04\u2013Nov\u00a013,\u00a02026',
        'source_sql':   'reportonhospitals.sql',
    },
}

js = (
    '/* Auto-generated by build_reports.py — do not edit by hand */\n'
    '/* Re-run build_reports.py after refreshing SQLExamples/reportonhospitals.json */\n'
    'window.HOSP = ' + json.dumps(payload, separators=(',', ':')) + ';\n'
)

with open(DEST, 'w', encoding='utf-8') as f:
    f.write(js)

print(f'Wrote {DEST}  ({len(js):,} chars,  {len(qes)} QEs,  {len(rows)} hospitals)')
